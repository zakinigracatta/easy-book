const en = Object.fromEntries(Object.entries(ar).map(([english, arabic]) => [arabic, english]));
const attributes = ['placeholder', 'title', 'aria-label'];

const translateValue = (value, language) => {
  const dictionary = language === 'ar' ? ar : en;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.trim();
  if (!core) return value;
  if (dictionary[core]) return `${leading}${dictionary[core]}${trailing}`;

  if (language === 'ar') {
    return value
      .replace(/Step (\d+) of (\d+)/g, 'الخطوة $1 من $2')
      .replace(/Edit Oct (\d+)/g, 'تعديل $1 أكتوبر')
      .replace(/\bAM\b/g, 'ص')
      .replace(/\bPM\b/g, 'م')
      .replace(/\b(\d+) reviews?\b/g, '$1 تقييمًا')
      .replace(/\b(\d+) mins?\b/g, '$1 دقيقة')
      .replace(/\b(\d+) hrs?\b/g, '$1 ساعة');
  }
  return value
    .replace(/الخطوة (\d+) من (\d+)/g, 'Step $1 of $2')
    .replace(/تعديل (\d+) أكتوبر/g, 'Edit Oct $1')
    .replace(/(\d+) تقييمًا/g, '$1 reviews')
    .replace(/(\d+) دقيقة/g, '$1 min')
    .replace(/(\d+) ساعة/g, '$1 hr')
    .replace(/(\d{1,2}:\d{2}) ص/g, '$1 AM')
    .replace(/(\d{1,2}:\d{2}) م/g, '$1 PM');
};

const translateElement = (element, language) => {
  attributes.forEach((attribute) => {
    if (element.hasAttribute?.(attribute)) {
      const current = element.getAttribute(attribute);
      const translated = translateValue(current, language);
      if (translated !== current) element.setAttribute(attribute, translated);
    }
  });
};

export const localizePage = (root, language) => {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    const translated = translateValue(root.nodeValue, language);
    if (translated !== root.nodeValue) root.nodeValue = translated;
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;

  translateElement(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const translated = translateValue(node.nodeValue, language);
      if (translated !== node.nodeValue) node.nodeValue = translated;
    } else {
      translateElement(node, language);
    }
    node = walker.nextNode();
  }
};
